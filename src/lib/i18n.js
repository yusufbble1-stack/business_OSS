export function getLang() {
  const saved = localStorage.getItem('as_perf_lang');
  if (saved === 'fr' || saved === 'en') return saved;
  // Browser language detection
  const browserLang = navigator.language || navigator.userLanguage;
  if (browserLang && browserLang.startsWith('fr')) {
    return 'fr';
  }
  return 'en';
}

export function setLang(lang) {
  if (lang === 'fr' || lang === 'en') {
    localStorage.setItem('as_perf_lang', lang);
    document.documentElement.setAttribute('lang', lang);
    window.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  }
}

export function t(key, replacements = {}, fallback = '') {
  const lang = getLang();
  let text = translations[lang]?.[key] || translations['en']?.[key] || fallback || key;
  Object.keys(replacements).forEach(k => {
    text = text.replace(`{${k}}`, replacements[k]);
  });
  return text;
}

// Initialize document.documentElement lang attribute
try {
  document.documentElement.setAttribute('lang', getLang());
} catch (e) {
  console.warn('[i18n] Failed to set initial document lang:', e);
}

